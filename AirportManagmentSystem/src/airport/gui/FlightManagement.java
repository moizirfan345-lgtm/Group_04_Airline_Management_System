// Search Flight
private void searchFlight() {

    String flightID = txtFlightID.getText().trim();

    if (flightID.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter Flight ID to search!");
        return;
    }

    boolean found = airportService.getHashTable()
            .searchFlight(flightID);

    if (found) {

        int row = findFlightRow(flightID);

        if (row >= 0) {
            tblFlights.setRowSelectionInterval(row, row);

            txtDestination.setText(
                    flightTableModel.getValueAt(row, 1).toString());

            txtPriority.setText(
                    flightTableModel.getValueAt(row, 2).toString());
        }

        JOptionPane.showMessageDialog(this,
                "Flight Found Successfully!");

    } else {
        JOptionPane.showMessageDialog(this,
                "Flight Not Found!");
    }
}


// Delete Flight
private void deleteFlight() {

    String flightID = txtFlightID.getText().trim();

    if (flightID.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter Flight ID to delete!");
        return;
    }

    boolean found = airportService.getHashTable()
            .searchFlight(flightID);

    if (found) {

        airportService.getHashTable().deleteFlight(flightID);

        int row = findFlightRow(flightID);

        if (row >= 0) {
            flightTableModel.removeRow(row);
        }

        JOptionPane.showMessageDialog(this,
                "Flight Deleted Successfully!");

        clearFields();

    } else {
        JOptionPane.showMessageDialog(this,
                "Flight Not Found!");
    }
}


// Clear Fields
private void clearFields() {

    txtFlightID.setText("");
    txtDestination.setText("");
    txtPriority.setText("");

    tblFlights.clearSelection();
}


// Find Flight Row in JTable
private int findFlightRow(String flightID) {

    for (int i = 0; i < flightTableModel.getRowCount(); i++) {

        String id = flightTableModel.getValueAt(i, 0).toString();

        if (id.equalsIgnoreCase(flightID)) {
            return i;
        }
    }

    return -1;
}

