    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
       String flightID = txtFlightID.getText().trim();
    String destination = txtDestination.getText().trim();
    String priorityText = txtPriority.getText().trim();

    // Check empty fields
    if (flightID.isEmpty() || destination.isEmpty()
            || priorityText.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill all fields!");
        return;
    }

    try {
        int priority = Integer.parseInt(priorityText);

        // Priority must be 1, 2 or 3
        if (priority < 1 || priority > 3) {
            JOptionPane.showMessageDialog(this,
                    "Priority must be 1, 2 or 3!");
            return;
        }

        // Check duplicate Flight ID
        if (airportService.getHashTable()
                .searchFlight(flightID)) {

            JOptionPane.showMessageDialog(this,
                    "Flight ID already exists!");
            return;
        }

        // Insert into existing Hash Table
        airportService.getHashTable()
                .insertFlight(flightID, destination);

        // Display in JTable
        flightTableModel.addRow(new Object[]{
            flightID, destination, priority
        });

        JOptionPane.showMessageDialog(this,
                "Flight Added Successfully!");

        // Clear input fields
        clearFields();

    } catch (NumberFormatException e) {

        JOptionPane.showMessageDialog(this,
                "Priority must be a number!");
    }
    }//GEN-LAST:event_btnAddActionPerformed

