private void addPassenger() {

    String id = txtPassengerID.getText().trim();
    String name = txtPassengerName.getText().trim();
    String ticket = txtContact.getText().trim();
    String flight = txtPassport.getText().trim();

    if (id.isEmpty() || name.isEmpty()
            || ticket.isEmpty() || flight.isEmpty()) {

        JOptionPane.showMessageDialog(this,
                "Please fill all fields!");
        return;
    }

    Passenger passenger =
            new Passenger(id, name, ticket, flight);

    boolean added =
            airportService.getPassengerList()
                    .addPassenger(passenger);

    if (added) {

        DefaultTableModel model =
                (DefaultTableModel) tblPassengers.getModel();

        model.addRow(new Object[]{
            id, name, ticket, flight
        });

        JOptionPane.showMessageDialog(this,
                "Passenger Added Successfully!");

        clearFields();

    } else {

        JOptionPane.showMessageDialog(this,
                "Passenger ID already exists!");
    }
}


private void searchPassenger() {

    String id = txtPassengerID.getText().trim();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter Passenger ID to search!");
        return;
    }

    Passenger passenger =
            airportService.getPassengerList()
                    .searchPassenger(id);

    if (passenger != null) {

        txtPassengerID.setText(passenger.getPassengerID());
        txtPassengerName.setText(passenger.getName());
        txtContact.setText(passenger.getTicketNumber());
        txtPassport.setText(passenger.getFlightNumber());

        JOptionPane.showMessageDialog(this,
                "Passenger Found!");

    } else {

        JOptionPane.showMessageDialog(this,
                "Passenger Not Found!");
    }
}


private void deletePassenger() {

    String id = txtPassengerID.getText().trim();

    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this,
                "Enter Passenger ID to delete!");
        return;
    }

    boolean deleted =
            airportService.getPassengerList()
                    .deletePassenger(id);

    if (deleted) {

        DefaultTableModel model =
                (DefaultTableModel) tblPassengers.getModel();

        for (int i = 0; i < model.getRowCount(); i++) {

            if (model.getValueAt(i, 0).toString()
                    .equalsIgnoreCase(id)) {

                model.removeRow(i);
                break;
            }
        }

        JOptionPane.showMessageDialog(this,
                "Passenger Deleted Successfully!");

        clearFields();

    } else {

        JOptionPane.showMessageDialog(this,
                "Passenger Not Found!");
    }
}


private void clearFields() {

    txtPassengerID.setText("");
    txtPassengerName.setText("");
    txtContact.setText("");
    txtPassport.setText("");

    tblPassengers.clearSelection();
}


 


