private void loadPassengers() {

    cboPassenger.removeAllItems();

    for (Passenger p : airportService.getPassengerList().getAllPassengers()) {

        cboPassenger.addItem(
            p.getPassengerID() + " - " + p.getName()
        );
    }
}

